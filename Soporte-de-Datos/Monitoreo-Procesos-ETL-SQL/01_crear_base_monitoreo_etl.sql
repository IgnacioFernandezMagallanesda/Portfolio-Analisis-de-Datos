-- =====================================================
-- Proyecto 2 - Monitoreo de procesos ETL y tickets
-- Base: monitoreo_etl (MySQL 8)
-- Escenario: cinco procesos automáticos cargan datos todas
-- las noches. Cada corrida queda registrada en la tabla
-- ejecuciones, y los incidentes se gestionan como tickets.
-- Período: octubre 2026. Fecha de corte: 31/10/2026 23:59.
-- Datos ficticios, creados para practicar.
-- =====================================================

DROP DATABASE IF EXISTS monitoreo_etl;
CREATE DATABASE monitoreo_etl;
USE monitoreo_etl;

-- Catálogo de procesos programados (todos corren una vez por día)
CREATE TABLE procesos (
    id_proceso       INT PRIMARY KEY,
    nombre           VARCHAR(40),
    origen           VARCHAR(40),
    destino          VARCHAR(40),
    hora_programada  TIME,
    duracion_esperada_min INT
);

-- Registro de cada corrida de un proceso
CREATE TABLE ejecuciones (
    id_ejecucion     INT PRIMARY KEY,
    id_proceso       INT,
    inicio           DATETIME,
    fin              DATETIME,
    estado           VARCHAR(10),
    filas_leidas     INT,
    filas_cargadas   INT,
    mensaje_error    VARCHAR(80)
);

-- Tiempo máximo de resolución según la prioridad del ticket
CREATE TABLE sla (
    prioridad        VARCHAR(10) PRIMARY KEY,
    horas_resolucion INT
);

-- Tickets de soporte
CREATE TABLE tickets (
    id_ticket        INT PRIMARY KEY,
    id_ejecucion     INT,
    apertura         DATETIME,
    cierre           DATETIME,
    prioridad        VARCHAR(10),
    estado           VARCHAR(15),
    equipo_asignado  VARCHAR(30),
    descripcion      VARCHAR(80)
);

